Object.entries(requirementDetailCatalog).forEach(([id, detail]) => {
  if (requirementCatalog[id]) requirementCatalog[id].detail = detail;
});

export function requirementsForPage(pathname, mode) {
  return Object.entries(requirementCatalog)
    .filter(([, item]) => item.routes.some((route) => route === "*" || (route.endsWith("*") ? pathname.startsWith(route.slice(0, -1)) : route === pathname)))
    .filter(([, item]) => !item.modes || item.modes.includes(mode))
    .map(([id, item]) => ({ id, ...item }));
}

